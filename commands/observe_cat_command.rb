  def initialize(sheet)
    @sheet = sheet
  end

  def match?(content)
    content.include?("[관찰]")
  end

  def execute(content:, account:, status_id:)
    return "먼저 `[등록/캐릭터명]`을 해주세요." unless @sheet.registered?(account)

    cat = @sheet.cat(account)
    cat_name = cat[:name]
    dominant = dominant_trait(cat) || :none

    template = OBSERVATION_TEXTS[dominant].sample
    text = format(template, cat: cat_name)

    @sheet.update_cat(account, last_reaction: text)
    @sheet.log(account, "관찰", dominant.to_s)

    <<~TEXT.strip
      #{cat_name}을/를 관찰합니다.

      #{text}
    TEXT
  end

  private

  def dominant_trait(cat)
    values = {
      affection: cat[:affection],
      aggression: cat[:aggression],
      stability: cat[:stability],
      weirdness: cat[:weirdness],
      unknown: cat[:unknown]
    }

    return nil if values.values.all?(&:zero?)

    values.max_by { |_key, value| value }[0]
  end
